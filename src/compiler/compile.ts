import type {
  CompileResult,
  EditorEntry,
  GeneratedFile,
  SectionManifest,
  SettingDefinition,
} from '../shared/types';
import { validateManifest } from './validation';

function isSetting(entry: EditorEntry): entry is SettingDefinition {
  return entry.type !== 'header' && entry.type !== 'paragraph';
}

function cleanUndefined<T>(value: T): T {
  if (Array.isArray(value)) {
    return value.map(cleanUndefined).filter((item) => item !== undefined) as T;
  }
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .filter(([, item]) => item !== undefined)
        .map(([key, item]) => [key, cleanUndefined(item)]),
    ) as T;
  }
  return value;
}

function schemaEntry(entry: EditorEntry) {
  if (!isSetting(entry)) return cleanUndefined(entry);
  return cleanUndefined({
    type: entry.type,
    id: entry.id,
    label: entry.label,
    default: entry.default,
    info: entry.info,
    min: entry.min,
    max: entry.max,
    step: entry.step,
    unit: entry.unit,
    options: entry.options,
    accept: entry.accept,
    visible_if: entry.visible_if,
  });
}

function buildSchema(manifest: SectionManifest): string {
  const schema = cleanUndefined({
    name: manifest.name,
    tag: manifest.tag ?? 'section',
    class: manifest.className ?? `vso-shopify-wrapper vso-${manifest.handle}-wrapper`,
    limit: manifest.limit,
    max_blocks: manifest.blocks.length ? manifest.maxBlocks ?? 12 : undefined,
    enabled_on: manifest.enabledTemplates?.length ? { templates: manifest.enabledTemplates } : undefined,
    settings: manifest.settings.map(schemaEntry),
    blocks: manifest.blocks.map((block) => cleanUndefined({
      type: block.type,
      name: block.name,
      limit: block.limit,
      settings: block.settings.map(schemaEntry),
    })),
    presets: manifest.presets,
  });
  return JSON.stringify(schema, null, 2);
}

function normalizeLiquidAliases(liquid: string): string {
  return liquid
    .replace(/\{\{\s*settings\./g, '{{ section.settings.')
    .replace(/\{%\s*if\s+settings\./g, '{% if section.settings.')
    .replace(/\{%\s*unless\s+settings\./g, '{% unless section.settings.')
    .replace(/\{%\s*case\s+settings\./g, '{% case section.settings.')
    .replace(/\bsection_id\b/g, 'section.id');
}

function buildSectionLiquid(manifest: SectionManifest): string {
  const stylesheet = manifest.source.css.trim()
    ? `{{ '${manifest.handle}.css' | asset_url | stylesheet_tag }}`
    : '';
  const script = manifest.source.javascript?.trim()
    ? `<script src="{{ '${manifest.handle}.js' | asset_url }}" defer="defer"></script>`
    : '';
  const source = normalizeLiquidAliases(manifest.source.liquid.trim());
  return [
    `{%- comment -%}\n  Generated by ThemeBot — the autonomous Shopify theme builder.\n  Contract: v${manifest.contractVersion}\n  Handle: ${manifest.handle}\n{%- endcomment -%}`,
    stylesheet,
    source,
    script,
    `{% schema %}\n${buildSchema(manifest)}\n{% endschema %}`,
    '',
  ].filter(Boolean).join('\n\n');
}

function buildReadme(manifest: SectionManifest): string {
  return `# ${manifest.name}\n\n${manifest.description}\n\n## Install manually\n\n1. Upload \`assets/${manifest.handle}.css\` to the theme assets directory.\n2. Upload \`assets/${manifest.handle}.js\` when present.\n3. Upload \`sections/${manifest.handle}.liquid\` to the theme sections directory.\n4. Open Shopify's theme editor and add **${manifest.name}**.\n\nThe section includes a preset, so it appears in Shopify's Add section panel.\n`;
}

export function compileSection(input: unknown): CompileResult {
  const { manifest, issues } = validateManifest(input);
  if (!manifest || issues.some((issue) => issue.severity === 'error')) {
    return {
      valid: false,
      files: [],
      issues,
      stats: { settings: 0, blockTypes: 0, liquidBytes: 0, cssBytes: 0, javascriptBytes: 0 },
    };
  }

  const liquid = buildSectionLiquid(manifest);
  const files: GeneratedFile[] = [
    { path: `sections/${manifest.handle}.liquid`, content: liquid, language: 'liquid' },
  ];
  if (manifest.source.css.trim()) {
    files.push({ path: `assets/${manifest.handle}.css`, content: manifest.source.css.trim() + '\n', language: 'css' });
  }
  if (manifest.source.javascript?.trim()) {
    files.push({ path: `assets/${manifest.handle}.js`, content: manifest.source.javascript.trim() + '\n', language: 'javascript' });
  }
  files.push(
    { path: 'section-os.manifest.json', content: JSON.stringify(manifest, null, 2) + '\n', language: 'json' },
    { path: 'README.md', content: buildReadme(manifest), language: 'markdown' },
  );

  return {
    valid: true,
    files,
    issues,
    stats: {
      settings: manifest.settings.filter(isSetting).length,
      blockTypes: manifest.blocks.length,
      liquidBytes: Buffer.byteLength(liquid),
      cssBytes: Buffer.byteLength(manifest.source.css),
      javascriptBytes: Buffer.byteLength(manifest.source.javascript ?? ''),
    },
  };
}
